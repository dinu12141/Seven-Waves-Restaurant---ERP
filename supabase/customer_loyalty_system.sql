-- =====================================================
-- RPC FUNCTIONS DEPLOYED
-- =====================================================
-- rpc_calculate_loyalty_coins(p_order_id)
--   Returns coins that would be earned for an order
--
-- rpc_apply_loyalty_reward(p_order_id)
--   Main reward function. Idempotent. Called by trigger.
--   - Checks order is PAID and has customer_id
--   - Calculates coins using active loyalty_rules
--   - Creates/finds loyalty_accounts
--   - Creates loyalty_transaction of type 'earn'
--   - Calls rpc_recalculate_loyalty_tier
--
-- rpc_recalculate_loyalty_tier(p_loyalty_account_id)
--   Assigns correct tier based on current_coins
--
-- rpc_adjust_loyalty_coins(p_customer_id, p_delta, p_note)
--   Admin function. Requires admin/manager role.
--   Creates audit transaction of type 'adjust'.
--
-- get_my_loyalty_account()
--   Returns authenticated customer's loyalty info
--
-- get_loyalty_customer_list(search, tier_code, limit, offset)
--   Admin: paginated loyalty member list
--
-- get_loyalty_customer_detail(p_customer_id)
--   Admin: full detail for one loyalty customer
-- =====================================================

-- =====================================================
-- TRIGGERS DEPLOYED
-- =====================================================
-- trg_order_loyalty_reward (AFTER UPDATE ON orders)
--   Fires when payment_status changes to 'paid'
--   Calls rpc_apply_loyalty_reward(order_id)
--
-- trg_invoice_loyalty_reward (AFTER UPDATE ON invoices)
--   Fires when invoice payment_status = 'paid'
--   Also triggers loyalty reward
-- =====================================================

-- =====================================================
-- BUSINESS RULES
-- =====================================================
