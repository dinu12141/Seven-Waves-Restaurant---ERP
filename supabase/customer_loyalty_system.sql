-- STANDARD: 0–99 coins
-- SILVER:   100–249 coins
-- GOLD:     250+ coins
-- Realtime: loyalty_accounts + loyalty_transactions
--           published to supabase_realtime
-- Security: all writes are via SECURITY DEFINER RPCs
-- Idempotency: unique index on (order_id) WHERE type='earn'
