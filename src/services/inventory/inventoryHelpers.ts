/**
 * inventoryHelpers.ts — pure helpers for the Inventory module.
 *
 *  - Business-day date maths for Sri Lanka (Asia/Colombo, UTC+05:30, no DST).
 *    `new Date().toISOString().split('T')[0]` returns *yesterday* between
 *    00:00 and 05:30 local time, and `'YYYY-MM-DD' + 'T23:59:59'` sent to a
 *    timestamptz column is read by Postgres as UTC — shifting every filter
 *    window by 5h30m. Always build bounds with dayStartISO / dayEndExclusiveISO.
 *  - Paged fetch to get past PostgREST's 1000-row response cap.
 *  - Small domain helpers (stock status normalisation, system-linked docs,
 *    tab → permission gate for InventoryPage).
 */

export const INVENTORY_TZ_OFFSET = '+05:30'
const OFFSET_MS = (5 * 60 + 30) * 60 * 1000
const DATE_RE = /^\d{4}-\d{2}-\d{2}$/

const pad = (n: number) => String(n).padStart(2, '0')

/** 'YYYY-MM-DD' of the Colombo calendar day containing `d` (default: now). */
export function invBusinessDate(d: Date = new Date()): string {
  const s = new Date(d.getTime() + OFFSET_MS)
  return `${s.getUTCFullYear()}-${pad(s.getUTCMonth() + 1)}-${pad(s.getUTCDate())}`
}

/** Calendar arithmetic on a 'YYYY-MM-DD' string (timezone independent). */
export function invAddDays(dateStr: string, n: number): string {
  const [y, m, d] = dateStr.split('-').map(Number)
  const dt = new Date(Date.UTC(y!, m! - 1, d! + n))
  return `${dt.getUTCFullYear()}-${pad(dt.getUTCMonth() + 1)}-${pad(dt.getUTCDate())}`
}

/** ISO instant of 00:00 Colombo time on `dateStr` — inclusive lower bound (`.gte`). */
export function invDayStartISO(dateStr: string): string {
  if (!DATE_RE.test(String(dateStr || ''))) return dateStr
  return new Date(`${dateStr}T00:00:00${INVENTORY_TZ_OFFSET}`).toISOString()
}

/** ISO instant of 00:00 Colombo time on the day AFTER `dateStr` — exclusive upper bound (`.lt`). */
export function invDayEndExclusiveISO(dateStr: string): string {
  if (!DATE_RE.test(String(dateStr || ''))) return dateStr
  return invDayStartISO(invAddDays(dateStr, 1))
}

/** Colombo business date of a timestamp (for grouping rows by day). */
export function invDateOf(ts: string | number | Date): string {
  return invBusinessDate(new Date(ts))
}

/**
 * Normalise v_stock_on_hand.stock_status. Two view definitions exist in the
 * repo (lowercase `low_stock` vs uppercase `LOW_STOCK` / `OK` / `OVER_STOCK`);
 * the UI only understands the lowercase set.
 */
export function normalizeStockStatus(s: unknown): string {
  const v = String(s ?? '').trim().toLowerCase()
  if (v === 'ok' || v === '') return 'normal'
  if (v === 'over_stock') return 'overstock'
  if (v === 'low') return 'low_stock'
  return v
}

export function isLowOrOut(status: unknown): boolean {
  const s = normalizeStockStatus(status)
  return s === 'low_stock' || s === 'out_of_stock'
}

/**
 * An inventory document generated by another module (procurement GRN mirror,
 * purchase return GIN, KOT BOM deduction …) carries reference_id +
 * reference_type. Cancelling it from the Inventory screen would reverse stock
 * without reversing the source document / AP bill / GL, so the UI blocks it.
 */
export function isSystemLinkedDoc(doc: { reference_id?: unknown; reference_type?: unknown } | null | undefined): boolean {
  return !!(doc && doc.reference_id && doc.reference_type)
}

/** Split an array into chunks (keeps `.in()` URLs short). */
export function chunk<T>(arr: T[], size: number): T[][] {
  const out: T[][] = []
  for (let i = 0; i < arr.length; i += size) out.push(arr.slice(i, i + size))
  return out
}

/**
 * Fetch every row of a query in pages of `pageSize` (PostgREST caps responses
 * at 1000). `build` must return a fresh query each call (with a stable ORDER BY).
 */
export async function fetchAllPaged<T = any>(
  build: () => { range: (from: number, to: number) => PromiseLike<{ data: T[] | null; error: any }> },
  pageSize = 1000,
  maxRows = 50000,
): Promise<T[]> {
  const all: T[] = []
  for (let from = 0; from < maxRows; from += pageSize) {
    const { data, error } = await build().range(from, from + pageSize - 1)
    if (error) throw error
    const rows = data || []
    all.push(...rows)
    if (rows.length < pageSize) break
  }
  return all
}

/** InventoryPage ?tab= value → permission required to view it. */
export const INVENTORY_TAB_PERMISSIONS: Record<string, string> = {
  dashboard: 'inventory.dashboard.view',
  items: 'inventory.tab_items.view',
  menu_items: 'inventory.tab_menu_items.view',
  menu_categories: 'inventory.tab_menu_categories.view',
  menu_book: 'inventory.tab_menu_book.view',
  kitchen_mapping: 'inventory.tab_kitchen_mapping.view',
  recipes: 'inventory.tab_recipes.view',
  bom_margins: 'inventory.tab_recipes.view',
  stock: 'inventory.tab_stock.view',
  warehouses: 'inventory.tab_warehouses.view',
  ledger: 'inventory.tab_ledger.view',
  wastage: 'inventory.tab_wastage.view',
  documents: 'inventory.tab_documents.view',
  'doc-create': 'inventory.tab_documents.view',
}

/**
 * Resolve the requested ?tab= into a tab that exists and the user may see.
 * Unknown tabs previously rendered an empty card; unpermitted tabs were
 * reachable by URL because the route only gates the page as a whole.
 */
export function resolveInventoryTab(
  requested: unknown,
  can: (perm: string) => boolean,
): { tab: string; denied: boolean } {
  const t = typeof requested === 'string' ? requested : ''
  const perm = INVENTORY_TAB_PERMISSIONS[t]
  if (!perm) return { tab: 'dashboard', denied: false }
  if (!can(perm)) return { tab: 'dashboard', denied: true }
  return { tab: t, denied: false }
}
