/**
 * Flat list of all reports for search
 */
export const ALL_REPORTS = REPORT_GROUPS.flatMap((g) =>
  g.reports.map((r) => ({ ...r, group: g.label, groupId: g.id, groupIcon: g.icon, groupColor: g.color })),
)

/**
 * Search reports by keyword
 */
export function searchReports(query) {
  if (!query) return ALL_REPORTS
  const q = query.toLowerCase()
  return ALL_REPORTS.filter(
    (r) =>
      r.label.toLowerCase().includes(q) ||
      r.description.toLowerCase().includes(q) ||
      r.group.toLowerCase().includes(q),
  )
}
