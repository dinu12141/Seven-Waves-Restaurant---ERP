// ── Currency & Number Formatters ──────────────────────────────────────
export function fmtLKR(val) {
  return `LKR ${Number(val || 0).toLocaleString('en-LK', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`
}

export function fmtNumber(val, decimals = 0) {
  return Number(val || 0).toLocaleString('en-LK', {
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals,
  })
}

export function fmtPercent(val) {
  return `${Number(val || 0).toFixed(2)}%`
}

// ── Date Formatters ───────────────────────────────────────────────────
export function fmtDate(dt) {
  if (!dt) return '—'
  return new Date(dt).toLocaleDateString('en-GB', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
  })
}

export function fmtDateTime(dt) {
  if (!dt) return '—'
  return new Date(dt).toLocaleString('en-GB', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  })
}

export function fmtTime(dt) {
  if (!dt) return '—'
  return new Date(dt).toLocaleTimeString('en-GB', {
    hour: '2-digit',
    minute: '2-digit',
  })
}

// ── Filter Builder ────────────────────────────────────────────────────
/**
 * Applies common report filters to a Supabase query.
 * @param {object} query - Supabase query builder
 * @param {object} filters - { dateFrom, dateTo, branch, ... }
 * @param {object} opts - { dateField: 'created_at', branchField: 'branch_id' }
 */
export function applyFilters(query, filters = {}, opts = {}) {
  const dateField = opts.dateField || 'created_at'
  const branchField = opts.branchField || 'branch_id'

  if (filters.dateFrom) {
    query = query.gte(dateField, filters.dateFrom + 'T00:00:00')
  }
  if (filters.dateTo) {
    query = query.lte(dateField, filters.dateTo + 'T23:59:59')
  }
  if (filters.branch) {
    query = query.eq(branchField, filters.branch)
  }

  return query
}

/**
 * Applies branch security — non-admin users only see their branch data.
 */
export function applyBranchSecurity(query, branchField = 'branch_id') {
  const authStore = useAuthStore()
  if (!authStore.isAdmin) {
    const branchId = authStore.currentBranch?.id
    if (branchId) query = query.eq(branchField, branchId)
  }
  return query
}

/**
 * Returns the current company_id from the auth store.
 */
export function getCompanyId() {
  const authStore = useAuthStore()
  return authStore.currentBranch?.company_id || authStore.profile?.company_id
}

// ── Simple Query Cache ────────────────────────────────────────────────
const _cache = new Map()
const CACHE_TTL = 60_000 // 1 minute

export function getCached(key) {
  const entry = _cache.get(key)
  if (entry && Date.now() - entry.ts < CACHE_TTL) return entry.data
  return null
}

export function setCache(key, data) {
  _cache.set(key, { data, ts: Date.now() })
}

export function clearCache(keyPrefix) {
  for (const k of _cache.keys()) {
    if (!keyPrefix || k.startsWith(keyPrefix)) _cache.delete(k)
  }
}

